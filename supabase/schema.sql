create or replace view v_clientes_ultima_compra with (security_invoker = true) as
  select c.codigo, c.nome, c.contato, c.telefone, c.whatsapp, c.celular, c.cidade, c.email,
         max(p.data) as ultimadata, max(p.pedido) as ultimopedido
  from clientes c left join pedidos p on p.codcli = c.codigo and coalesce(p.s,'A') <> 'C'
  where c.ativo
  group by c.codigo;

create or replace view v_remessas with (security_invoker = true) as
  select cobranca as numero, min(data) as data, min(codfor) as codfor, min(fornecedor) as fornecedor,
         count(*) as titulos, sum(coalesce(total, valor)) as total,
         min(depnome) as depnome, min(depbanco) as depbanco
  from cobranca where cobranca is not null group by cobranca;

create or replace function rel_compras_cliente(cod integer)
returns table (codfor integer, fornecedor text, produto integer, nomeproduto text, forn text, vezes bigint, quant numeric, ultima date)
language sql stable as $$
  select pp.codfor, coalesce(f.nome, max(pe.fornecedor)), pp.produto, max(pp.nomeproduto), max(pp.forn),
         count(*), sum(pp.quant), max(pp.data)
  from produtospedido pp
  join pedidos pe on pe.pedido = pp.pedido and coalesce(pe.s,'A') <> 'C'
  left join fornecedores f on f.codigo = pp.codfor
  where pe.codcli = cod
  group by pp.codfor, f.nome, pp.produto
  order by 2, 4;
$$;

create or replace function rel_clientes_representada_ano(cod integer)
returns table (codcli integer, cliente text, cidade text, ano integer, pedidos bigint, total numeric)
language sql stable as $$
  select p.codcli, max(p.cliente), max(c.cidade), extract(year from p.data)::int, count(*), sum(p.total)
  from pedidos p left join clientes c on c.codigo = p.codcli
  where p.codfor = cod and coalesce(p.s,'A') <> 'C'
  group by p.codcli, extract(year from p.data)
  order by 2, 4;
$$;

create or replace function rel_vendas(ini date, fim date, cod integer default null)
returns table (codfor integer, fornecedor text, pedidos bigint, total numeric, comissao numeric)
language sql stable as $$
  select p.codfor, max(p.fornecedor), count(*), sum(p.total), sum(p.vrcomissao)
  from pedidos p
  where p.data between ini and fim and coalesce(p.s,'A') <> 'C' and (cod is null or p.codfor = cod)
  group by p.codfor order by 4 desc;
$$;

create or replace function resumo_painel() returns jsonb language sql stable as $$
  select jsonb_build_object(
    'pedidos_mes', (select count(*) from pedidos where date_trunc('month', data) = date_trunc('month', current_date) and coalesce(s,'A') <> 'C'),
    'vendas_mes', (select coalesce(sum(total),0) from pedidos where date_trunc('month', data) = date_trunc('month', current_date) and coalesce(s,'A') <> 'C'),
    'comissao_mes', (select coalesce(sum(vrcomissao),0) from pedidos where date_trunc('month', data) = date_trunc('month', current_date) and coalesce(s,'A') <> 'C'),
    'comissao_aberta', (select coalesce(sum(vrcomissao),0) from controlevendas where codacerto is null),
    'cobranca_aberta', (select coalesce(sum(valor),0) from cobranca where cobranca is null),
    'cobranca_vencida', (select count(*) from cobranca where cobranca is null and vencimento < current_date),
    'preposto_aberto', (select coalesce(sum(coalesce(comissaoentrega, vrcomissao)),0) from preposto where acerto is null)
  );
$$;

create or replace view v_cartacobranca with (security_invoker = true) as
  select c.*, cl.nome as nomecliente, f.nome as nomefornecedor
  from cartacobranca c
  left join clientes cl on cl.codigo = c.cliente
  left join fornecedores f on f.codigo = c.fornecedor;

create or replace view v_fornecedorescontas with (security_invoker = true) as
  select c.*, f.nome as nomerepresentada
  from fornecedorescontas c left join fornecedores f on f.codigo = c.representada;
