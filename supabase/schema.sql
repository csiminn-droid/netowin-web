-- ---------------------------------------------------------------------
-- Segurança: só usuários cadastrados em "usuarios" enxergam os dados
-- ---------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array['sistema','clientes','fornecedores','fornecedorescontas','contas','tipoproduto','produtos',
    'transportadoras','vendedor','pedidos','produtospedido','acerto','controlevendas','debitocredito',
    'acertovendedor','preposto','vales','cobranca','cheques','cartacobranca'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists acesso on %I', t);
    execute format('create policy acesso on %I for all to authenticated using (autorizado()) with check (autorizado())', t);
  end loop;
end $$;
alter table usuarios enable row level security;
drop policy if exists ver_proprio on usuarios;
create policy ver_proprio on usuarios for select to authenticated using (autorizado());

