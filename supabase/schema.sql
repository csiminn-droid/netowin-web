create or replace function exigir_acesso() returns void language plpgsql as $$
begin
  if not autorizado() then raise exception 'Acesso não autorizado'; end if;
end $$;

-- Ajusta os contadores depois de importar os dados antigos
create or replace function ajustar_sequencias() returns void language plpgsql as $$
declare r record; m bigint;
begin
  perform exigir_acesso();
  for r in select * from (values
    ('clientes','codigo'),('fornecedores','codigo'),('fornecedorescontas','id'),('contas','id'),
    ('tipoproduto','codigo'),('produtos','codigo'),('transportadoras','codigo'),('vendedor','codigo'),
    ('pedidos','pedido'),('produtospedido','id'),('acerto','acerto'),('controlevendas','id'),
    ('debitocredito','id'),('acertovendedor','acerto'),('preposto','id'),('vales','id'),
    ('cobranca','id'),('cheques','id'),('cartacobranca','id')) as v(t, c) loop
    execute format('select coalesce(max(%I),0) from %I', r.c, r.t) into m;
    perform setval(pg_get_serial_sequence(r.t, r.c), greatest(m, 1), m > 0);
  end loop;
  select coalesce(max(cobranca),0) into m from cobranca;
  perform setval('remessa_seq', greatest(m,1), m > 0);
end $$;

-- Apaga todos os dados (usado antes de importar de novo)
create or replace function limpar_dados() returns void language plpgsql as $$
begin
  perform exigir_acesso();
  truncate clientes, fornecedores, fornecedorescontas, contas, tipoproduto, produtos, transportadoras,
    vendedor, pedidos, produtospedido, acerto, controlevendas, debitocredito, acertovendedor,
    preposto, vales, cobranca, cheques, cartacobranca;
end $$;

-- ---------------------------------------------------------------------
-- Salvar pedido (cabeçalho + itens) e lançar comissões
-- p: dados do pedido (jsonb). itens: lista de itens.
-- p.lancar_preposto (bool) e p.comissao_preposto (%) controlam a comissão do vendedor.
-- ---------------------------------------------------------------------
create or replace function salvar_pedido(p jsonb, itens jsonb) returns integer language plpgsql as $$
declare
  num integer := nullif(p->>'pedido','')::integer;
  novo boolean := num is null or not exists (select 1 from pedidos where pedido = num);
  sub numeric := 0; tot numeric; d numeric; i int; dv numeric[] := array[0,0,0,0,0];
  com numeric := coalesce(nullif(p->>'comissao','')::numeric, 0);
  vrc numeric; status text := coalesce(nullif(p->>'s',''), 'A');
  cid text; vend record; it jsonb; ord int := 0; abertos int;
  pcom numeric := coalesce(nullif(p->>'comissao_preposto','')::numeric, 0);
begin
  perform exigir_acesso();
  for it in select * from jsonb_array_elements(itens) loop
    sub := sub + round(coalesce(nullif(it->>'quant','')::numeric,0) * coalesce(nullif(it->>'valor','')::numeric,0), 2);
  end loop;
  tot := sub;
  for i in 1..5 loop
    d := coalesce(nullif(p->>('desc'||i),'')::numeric, 0);
    dv[i] := round(tot * d / 100, 4);
    tot := tot - dv[i];
  end loop;
  tot := round(tot, 4);
  vrc := round(tot * com / 100, 4);

  if novo then
    if num is null then
      insert into pedidos (data) values (coalesce(nullif(p->>'data','')::date, current_date)) returning pedido into num;
    else
      insert into pedidos (pedido) values (num);
    end if;
  end if;

  update pedidos set
    data = coalesce(nullif(p->>'data','')::date, current_date),
    pedidocliente = nullif(p->>'pedidocliente',''), datapedidocliente = nullif(p->>'datapedidocliente',''),
    comissao = com, vrcomissao = vrc,
    codcli = nullif(p->>'codcli','')::integer, cliente = nullif(p->>'cliente',''),
    codfor = nullif(p->>'codfor','')::integer, fornecedor = nullif(p->>'fornecedor',''),
    subtotal = sub, total = tot,
    desc1 = nullif(p->>'desc1','')::numeric, desc1v = dv[1], desc2 = nullif(p->>'desc2','')::numeric, desc2v = dv[2],
    desc3 = nullif(p->>'desc3','')::numeric, desc3v = dv[3], desc4 = nullif(p->>'desc4','')::numeric, desc4v = dv[4],
    desc5 = nullif(p->>'desc5','')::numeric, desc5v = dv[5],
    prazo = nullif(p->>'prazo',''), codtransp = nullif(p->>'codtransp','')::integer, transportadora = nullif(p->>'transportadora',''),
    vendedor = nullif(p->>'vendedor','')::integer,
    obs1 = nullif(p->>'obs1',''), obs2 = nullif(p->>'obs2',''), obs3 = nullif(p->>'obs3',''),
    entrega = nullif(p->>'entrega',''), tipocobr = nullif(p->>'tipocobr',''), tipovenda = nullif(p->>'tipovenda',''),
    s = status
  where pedido = num;

  delete from produtospedido where pedido = num;
  for it in select * from jsonb_array_elements(itens) loop
    ord := ord + 1;
    insert into produtospedido (pedido, ordem, produto, nomeproduto, unid, forn, quant, valor, subtotal, ipi, caixa,
      comissao, codfor, codcli, data, naoenviado, quantenviado, subtotalenviado)
    values (num, ord, nullif(it->>'produto','')::integer, it->>'nomeproduto', nullif(it->>'unid',''), nullif(it->>'forn',''),
      nullif(it->>'quant','')::numeric, nullif(it->>'valor','')::numeric,
      round(coalesce(nullif(it->>'quant','')::numeric,0) * coalesce(nullif(it->>'valor','')::numeric,0), 2),
      nullif(it->>'ipi','')::numeric, nullif(it->>'caixa','')::numeric, com,
      nullif(p->>'codfor','')::integer, nullif(p->>'codcli','')::integer, coalesce(nullif(p->>'data','')::date, current_date),
      nullif(it->>'naoenviado',''), nullif(it->>'quantenviado','')::numeric,
      case when nullif(it->>'quantenviado','') is null then null
           else round((it->>'quantenviado')::numeric * coalesce(nullif(it->>'valor','')::numeric,0), 2) end);
  end loop;

  select cidade into cid from clientes where codigo = nullif(p->>'codcli','')::integer;

  if status = 'C' then
    delete from controlevendas where pedido = num and codacerto is null;
    delete from preposto where pedido = num and acerto is null;
    return num;
  end if;

  -- Controle de vendas: cria na inclusão; na alteração atualiza se houver um único lançamento em aberto e sem entrega
  select count(*) into abertos from controlevendas where pedido = num;
  if abertos = 0 then
    insert into controlevendas (data, comissao, vrcomissao, codcli, cliente, codfor, fornecedor, total, pedido, ref, cidade)
    values (coalesce(nullif(p->>'data','')::date, current_date), com, vrc, nullif(p->>'codcli','')::integer, nullif(p->>'cliente',''),
      nullif(p->>'codfor','')::integer, nullif(p->>'fornecedor',''), tot, num, num::text, cid);
  elsif abertos = 1 then
    update controlevendas set comissao = com, vrcomissao = vrc, total = tot,
      codcli = nullif(p->>'codcli','')::integer, cliente = nullif(p->>'cliente',''),
      codfor = nullif(p->>'codfor','')::integer, fornecedor = nullif(p->>'fornecedor',''), cidade = cid
    where pedido = num and codacerto is null and coalesce(entrega,0) = 0;
  end if;

  -- Comissão do preposto
  if coalesce((p->>'lancar_preposto')::boolean, false) and nullif(p->>'vendedor','') is not null then
    select * into vend from vendedor where codigo = (p->>'vendedor')::integer;
    if exists (select 1 from preposto where pedido = num and acerto is null) then
      update preposto set codven = vend.codigo, vendedor = vend.nome, total = tot, comissao = pcom,
        vrcomissao = round(tot * pcom / 100, 4), comissaoentrega = round(tot * pcom / 100, 4), entrega = tot,
        codcli = nullif(p->>'codcli','')::integer, cliente = nullif(p->>'cliente',''),
        codfor = nullif(p->>'codfor','')::integer, fornecedor = nullif(p->>'fornecedor',''), cidade = cid
      where pedido = num and acerto is null;
    elsif not exists (select 1 from preposto where pedido = num) then
      insert into preposto (codven, vendedor, data, ref, pedido, total, vrcomissao, comissao, codcli, cliente, codfor, fornecedor,
        cidade, entrega, comissaoentrega)
      values (vend.codigo, vend.nome, coalesce(nullif(p->>'data','')::date, current_date), num::text, num, tot,
        round(tot * pcom / 100, 4), pcom, nullif(p->>'codcli','')::integer, nullif(p->>'cliente',''),
        nullif(p->>'codfor','')::integer, nullif(p->>'fornecedor',''), cid, tot, round(tot * pcom / 100, 4));
    end if;
  elsif not coalesce((p->>'lancar_preposto')::boolean, false) and p ? 'lancar_preposto' then
    delete from preposto where pedido = num and acerto is null;
  end if;

  return num;
end $$;

create or replace function excluir_pedido(num integer) returns void language plpgsql as $$
begin
  perform exigir_acesso();
  if exists (select 1 from controlevendas where pedido = num and codacerto is not null) then
    raise exception 'Este pedido já entrou num acerto com a representada. Cancele o pedido em vez de excluir.';
  end if;
  delete from produtospedido where pedido = num;
  delete from controlevendas where pedido = num and codacerto is null;
  delete from preposto where pedido = num and acerto is null;
  delete from pedidos where pedido = num;
end $$;

-- ---------------------------------------------------------------------
-- Acerto com a representada
-- ---------------------------------------------------------------------
create or replace function fazer_acerto(cod integer, vendas_ids bigint[], dc_ids bigint[], p jsonb) returns integer
language plpgsql as $$
declare f record; n integer; v numeric; c numeric; dc numeric;
begin
  perform exigir_acesso();
  select * into f from fornecedores where codigo = cod;
  select coalesce(sum(total),0), coalesce(sum(vrcomissao),0) into v, c
    from controlevendas where id = any(vendas_ids) and codfor = cod and codacerto is null;
  select coalesce(sum(total),0) into dc from debitocredito where id = any(coalesce(dc_ids, '{}')) and codfor = cod and codacerto is null;
  insert into acerto (codfor, fornecedor, vendas, comissao, debitocredito, receber, data, obs1, obs2, obs3,
    banconome, bancocpfcnpj, bancobanco, bancoagencia, bancoconta, bancotexto,
    fornecedorrua, fornecedorbairro, fornecedorcidade, fornecedoruf, fornecedorcep, fornecedortelefone,
    fornecedoremail, fornecedorcgc, fornecedorinsc)
  values (cod, coalesce(f.nome, p->>'fornecedor'), v, c, dc, round(c + dc, 2), coalesce(nullif(p->>'data','')::date, current_date),
    nullif(p->>'obs1',''), nullif(p->>'obs2',''), nullif(p->>'obs3',''),
    nullif(p->>'banconome',''), nullif(p->>'bancocpfcnpj',''), nullif(p->>'bancobanco',''), nullif(p->>'bancoagencia',''),
    nullif(p->>'bancoconta',''), nullif(p->>'bancotexto',''),
    f.rua, f.bairro, f.cidade, f.uf, f.cep, f.telefone, f.email, f.cgc, f.insc)
  returning acerto into n;
  update controlevendas set codacerto = n, datapag = coalesce(datapag, coalesce(nullif(p->>'data','')::date, current_date))
    where id = any(vendas_ids) and codfor = cod and codacerto is null;
  update debitocredito set codacerto = n where id = any(coalesce(dc_ids, '{}')) and codfor = cod and codacerto is null;
  return n;
end $$;

create or replace function desfazer_acerto(n integer) returns void language plpgsql as $$
begin
  perform exigir_acesso();
  update controlevendas set codacerto = null where codacerto = n;
  update debitocredito set codacerto = null where codacerto = n;
  delete from acerto where acerto = n;
end $$;

-- ---------------------------------------------------------------------
-- Acerto de preposto
-- ---------------------------------------------------------------------
create or replace function fazer_acerto_preposto(cod integer, com_ids bigint[], vale_ids bigint[], p jsonb) returns integer
language plpgsql as $$
declare v record; n integer; c numeric; va numeric;
begin
  perform exigir_acesso();
  select * into v from vendedor where codigo = cod;
  select coalesce(sum(coalesce(comissaoentrega, vrcomissao)),0) into c from preposto where id = any(com_ids) and codven = cod and acerto is null;
  select coalesce(sum(valor),0) into va from vales where id = any(coalesce(vale_ids,'{}')) and codven = cod and acerto is null;
  insert into acertovendedor (codigo, nomevendedor, nome, banco, agencia, conta, obs, data, valor)
  values (cod, v.nome, nullif(p->>'nome',''), coalesce(nullif(p->>'banco',''), v.banco), coalesce(nullif(p->>'agencia',''), v.agencia),
    coalesce(nullif(p->>'conta',''), v.conta), nullif(p->>'obs',''), coalesce(nullif(p->>'data','')::date, current_date), round(c + va, 2))
  returning acerto into n;
  update preposto set acerto = n, datapag = coalesce(nullif(p->>'data','')::date, current_date)
    where id = any(com_ids) and codven = cod and acerto is null;
  update vales set acerto = n where id = any(coalesce(vale_ids,'{}')) and codven = cod and acerto is null;
  return n;
end $$;

create or replace function desfazer_acerto_preposto(n integer) returns void language plpgsql as $$
begin
  perform exigir_acesso();
  update preposto set acerto = null where acerto = n;
  update vales set acerto = null where acerto = n;
  delete from acertovendedor where acerto = n;
end $$;

-- ---------------------------------------------------------------------
-- Remessa de cobrança: marca títulos como recebidos e registra cheques/depósitos
-- ---------------------------------------------------------------------
create or replace function registrar_remessa(titulo_ids bigint[], p jsonb, docs jsonb) returns integer
language plpgsql as $$
declare n integer := nextval('remessa_seq'); d jsonb; primeiro bigint;
begin
  perform exigir_acesso();
  if coalesce(array_length(titulo_ids,1),0) = 0 then raise exception 'Escolha pelo menos um título'; end if;
  update cobranca set cobranca = n, data = coalesce(nullif(p->>'data','')::date, current_date), total = valor, vjuros = 0,
    obs1 = coalesce(nullif(p->>'obs1',''), obs1), obs2 = coalesce(nullif(p->>'obs2',''), obs2), obs3 = coalesce(nullif(p->>'obs3',''), obs3),
    depnome = nullif(p->>'depnome',''), depbanco = nullif(p->>'depbanco',''), depagencia = nullif(p->>'depagencia',''),
    depconta = nullif(p->>'depconta',''), deptexto = nullif(p->>'deptexto','')
  where id = any(titulo_ids) and cobranca is null;
  select min(id) into primeiro from cobranca where cobranca = n;
  update cobranca set vjuros = coalesce(nullif(p->>'vjuros','')::numeric,0), total = valor + coalesce(nullif(p->>'vjuros','')::numeric,0)
    where id = primeiro;
  for d in select * from jsonb_array_elements(coalesce(docs,'[]')) loop
    insert into cheques (cobranca, banco, numero, datavenc, valor, obs)
    values (n, nullif(d->>'banco',''), nullif(d->>'numero',''), nullif(d->>'datavenc','')::date, nullif(d->>'valor','')::numeric, nullif(d->>'obs',''));
  end loop;
  return n;
end $$;

create or replace function desfazer_remessa(n integer) returns void language plpgsql as $$
begin
  perform exigir_acesso();
  update cobranca set cobranca = null, data = null, total = null, vjuros = null,
    depnome = null, depbanco = null, depagencia = null, depconta = null, deptexto = null where cobranca = n;
  delete from cheques where cobranca = n;
end $$;

